CREATE TABLE store (
 id TEXT PRIMARY KEY, "ownerId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
 name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 120),
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "store_ownerId_idx" ON store("ownerId");
CREATE TABLE image_asset (
 id TEXT PRIMARY KEY, "ownerId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
 "storageKey" TEXT NOT NULL UNIQUE, "mediaType" TEXT NOT NULL,
 width INTEGER NOT NULL, height INTEGER NOT NULL, size INTEGER NOT NULL,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE item ALTER COLUMN "priceCents" DROP NOT NULL;
ALTER TABLE item ADD COLUMN "storeId" TEXT REFERENCES store(id) ON DELETE CASCADE,
 ADD COLUMN "imageAssetId" TEXT REFERENCES image_asset(id), ADD COLUMN "externalUrl" TEXT,
 ADD COLUMN "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP;
CREATE TABLE item_placement (
 id TEXT PRIMARY KEY, "itemId" TEXT NOT NULL UNIQUE REFERENCES item(id) ON DELETE CASCADE,
 "worldId" TEXT NOT NULL, "surfaceId" TEXT NOT NULL,
 x DOUBLE PRECISION NOT NULL, y DOUBLE PRECISION NOT NULL, z DOUBLE PRECISION NOT NULL,
 yaw DOUBLE PRECISION NOT NULL, revision INTEGER NOT NULL DEFAULT 1,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Internal service tables have no client read/write policies.
CREATE TABLE game_ticket (
 hash TEXT PRIMARY KEY, "sessionId" TEXT NOT NULL REFERENCES session(id) ON DELETE CASCADE,
 "worldId" TEXT NOT NULL, "expiresAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE market_request (
 "userId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
 key TEXT NOT NULL, fingerprint TEXT NOT NULL, result JSONB NOT NULL,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY("userId", key)
);
CREATE TABLE market_rate (key TEXT PRIMARY KEY, count INTEGER NOT NULL, "expiresAt" TIMESTAMP(3) NOT NULL);
CREATE TABLE world_revision (id TEXT PRIMARY KEY, revision BIGINT NOT NULL DEFAULT 0);
INSERT INTO world_revision(id) VALUES ('demo_store');
CREATE FUNCTION bump_market_world() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN UPDATE world_revision SET revision = revision + 1 WHERE id = 'demo_store'; RETURN NULL; END $$;
CREATE TRIGGER placement_revision AFTER INSERT OR UPDATE OR DELETE ON item_placement FOR EACH STATEMENT EXECUTE FUNCTION bump_market_world();
CREATE TRIGGER item_revision AFTER UPDATE OR DELETE ON item FOR EACH STATEMENT EXECUTE FUNCTION bump_market_world();
CREATE TRIGGER store_revision AFTER UPDATE ON store FOR EACH STATEMENT EXECUTE FUNCTION bump_market_world();
